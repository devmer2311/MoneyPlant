class ThemePack {
  final String id, name, emoji;
  final GardenTokens light, dark;
  const ThemePack({
    required this.id,
    required this.name,
    required this.emoji,
    required this.light,
    required this.dark,
  });
  GardenTokens tokens(Brightness brightness) =>
      brightness == Brightness.dark ? dark : light;
}

