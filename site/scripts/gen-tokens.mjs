// Port of _palette() in packs.dart (only the roles the site uses).
function palette({ dark, brand, accent, secondary, canvas, surface }) {
  const hero = lerp(brand, '#08080C', 0.25);
  return {
    canvas, surface,
    surfaceAlt: lerp(surface, accent, 0.08),
    ink: dark ? '#F8F5F6' : '#19191E',
    inkMuted: dark ? '#C4BDC6' : '#57515B',
    brand: dark ? accent : brand,
    onBrand: dark ? '#19191E' : '#FFFFFF',
    receive: accent, onReceive: '#19191E',
    owe: secondary, onOwe: '#19191E',
    hero, heroGrad1: hero, heroGrad2: lerp(hero, '#000000', 0.5),
    heroInk: '#FFFFFF', heroMuted: '#EAE5ED',
    coinHi: '#FFEDAB', coinShade: '#D7BD72', coinEdge: '#B69C55', coinInk: '#897438',
    leafHi: accent, leafMid: lerp(accent, brand, 0.35), leafShade: brand,
    chart: [accent, secondary, '#FFCD91', '#A5D9F1', '#D2C4FA', '#C5E9A3'],
  };
}

function pack(id, name, emoji, font, radius, brand, accent, secondary, canvas, darkCanvas, darkSurface) {
  const args = { brand: hex(brand), accent: hex(accent), secondary: hex(secondary) };
  return {
    id, name, emoji, font, radius,
    light: palette({ ...args, dark: false, canvas: hex(canvas), surface: '#FFFFFF' }),
    dark: palette({ ...args, dark: true, canvas: hex(darkCanvas), surface: hex(darkSurface) }),
  };
}

