const vars = (p, t) => `  --canvas: ${t.canvas};
  --surface: ${t.surface};
  --surface-alt: ${t.surfaceAlt};
  --ink: ${t.ink};
  --ink-muted: ${t.inkMuted};
  --brand: ${t.brand};
  --on-brand: ${t.onBrand};
  --receive: ${t.receive};
  --on-receive: ${t.onReceive};
  --owe: ${t.owe};
  --on-owe: ${t.onOwe};
  --hero: ${t.hero};
  --hero-grad-1: ${t.heroGrad1};
  --hero-grad-2: ${t.heroGrad2};
  --hero-ink: ${t.heroInk};
  --hero-muted: ${t.heroMuted};
  --coin-hi: ${t.coinHi};
  --coin-shade: ${t.coinShade};
  --coin-edge: ${t.coinEdge};
  --coin-ink: ${t.coinInk};
  --leaf-hi: ${t.leafHi};
  --leaf-mid: ${t.leafMid};
  --leaf-shade: ${t.leafShade};
${t.chart.map((c, i) => `  --chart-${i + 1}: ${c};`).join('\n')}
  --radius: ${p.radius}px;
  --font-display: '${p.font}', var(--font-body);`;

let css = `/* GENERATED by scripts/gen-tokens.mjs from the app's theme packs. Do not edit by hand. */
:root {
  --font-body: 'Manrope', system-ui, sans-serif;
}
`;
for (const p of packs) {
  for (const mode of ['dark', 'light']) {
    const sel =
      p.id === 'garden' && mode === 'dark'
        ? `:root,\n[data-theme='garden'][data-mode='dark']`
        : `[data-theme='${p.id}'][data-mode='${mode}']`;
    css += `\n${sel} {\n  color-scheme: ${mode};\n${vars(p, p[mode])}\n}\n`;
  }
}

const ts = `// GENERATED by scripts/gen-tokens.mjs from the app's theme packs. Do not edit by hand.
export type Mode = 'dark' | 'light';
export type ThemeTokens = {
  canvas: string; surface: string; surfaceAlt: string;
  ink: string; inkMuted: string; brand: string; onBrand: string;
  receive: string; onReceive: string; owe: string; onOwe: string;
  hero: string; heroGrad1: string; heroGrad2: string; heroInk: string; heroMuted: string;
  coinHi: string; coinShade: string; coinEdge: string; coinInk: string;
  leafHi: string; leafMid: string; leafShade: string;
  chart: string[];
};
export type ThemePack = {
  id: string; name: string; emoji: string; font: string; radius: number;
  light: ThemeTokens; dark: ThemeTokens;
};
export const themePacks: ThemePack[] = ${JSON.stringify(packs, null, 2)};
export const defaultTheme = 'garden';
export const defaultMode: Mode = 'dark';
export const themePack = (id: string): ThemePack =>
  themePacks.find((p) => p.id === id) ?? themePacks[0]!;
`;

mkdirSync(join(root, 'src/styles'), { recursive: true });
