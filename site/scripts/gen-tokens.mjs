// Generates src/styles/tokens.css and src/lib/themes.ts from the app's theme
// pack data (lib/core/theme/packs.dart + tokens.dart), porting Flutter's
// Color.lerp so site colours match the app exactly. Run: npm run gen:tokens
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const hex = (n) => '#' + n.toString(16).padStart(6, '0').toUpperCase();
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const lerp = (a, b, t) =>
  '#' +
  rgb(a)
    .map((c, i) => Math.round(c + (rgb(b)[i] - c) * t).toString(16).padStart(2, '0'))
    .join('')
    .toUpperCase();

